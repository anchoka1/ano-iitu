"""Маскирование личных данных: телефоны, банковские карты, ИИН.

Суть: превращаем «+7 701 123 45 67» в «+7 *** *** ** 67», а номер карты —
в «**** **** **** 1234». Используем регулярные выражения (regex) —
шаблоны для поиска кусков текста.
"""

from __future__ import annotations

import re

# Карта: 16–19 цифр, между цифрами могут быть пробелы или дефисы.
# (?:\d[ -]?){15,18}\d — «цифра и, возможно, разделитель» 15–18 раз, затем цифра.
# \b — граница слова, чтобы не цеплять кусок более длинного числа.
_CARD_RE = re.compile(r"\b(?:\d[ -]?){15,18}\d\b")

# ИИН (индивидуальный идентификационный номер в Казахстане): ровно 12 цифр.
_IIN_RE = re.compile(r"\b\d{12}\b")

# Телефон Казахстана/России: +7 или 8, затем 10 цифр с любыми разделителями.
# (?<!\d) — «перед этим нет цифры», чтобы не резать длинные числа.
_PHONE_RE = re.compile(
    r"(?<!\d)(?:\+7|8)[\s\-()]*\d{3}[\s\-()]*\d{3}[\s\-]*\d{2}[\s\-]*(\d{2})(?!\d)"
)


# Номера документов: паспорт РК (N + 8 цифр), удостоверение личности / паспорт / студенческий «№ 123456789»,
# серия и номер российского паспорта «45 12 345678».
_PASSPORT_RE = re.compile(r"\b[NnНн]\s?\d{8}\b")
_DOC_RE = re.compile(
    r"((?:удостоверени\w*|уд\.?\s*л\.?|паспорт\w*|студенческ\w*(?:\s+билет\w*)?|id[- ]?карт\w*|документ\w*)"
    r"[^\d\n]{0,25}?(?:№|N|номер)?\s*)(\d[\d\s]{5,14}\d)", re.IGNORECASE)
_RU_PASSPORT_RE = re.compile(r"\b\d{2}\s\d{2}\s\d{6}\b")


def _mask_card(match: re.Match[str]) -> str:
    digits = re.sub(r"\D", "", match.group(0))  # \D — всё, что не цифра
    return "**** **** **** " + digits[-4:]


def mask_sensitive(text: str) -> str:
    """Возвращает текст, в котором спрятаны карты, ИИН и телефоны.

    Порядок важен: сначала карты (самые длинные числа), потом ИИН,
    потом телефоны — иначе короткий шаблон «съел» бы часть длинного.
    """
    if not text:
        return text
    text = _CARD_RE.sub(_mask_card, text)
    text = _IIN_RE.sub("[ИИН скрыт]", text)
    text = _DOC_RE.sub(lambda m: m.group(1) + "[номер документа скрыт]", text)
    text = _PASSPORT_RE.sub("[номер документа скрыт]", text)
    text = _RU_PASSPORT_RE.sub("[номер документа скрыт]", text)
    # \1 — подставить то, что попало в первые круглые скобки (последние 2 цифры)
    text = _PHONE_RE.sub(r"+7 *** *** ** \1", text)
    return text
