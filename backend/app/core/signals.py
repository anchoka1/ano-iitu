from dataclasses import dataclass, field


@dataclass(frozen=True)
class SignalRule:
    id: str
    title: str        # короткое название приёма
    explanation: str  # почему это опасно — простым языком
    weight: int       # «вес» признака: 1 — подозрительно, 2–3 — сильный признак
    patterns: tuple[str, ...]


@dataclass
class SignalHit:
    id: str
    title: str
    explanation: str
    weight: int
    quotes: list[str] = field(default_factory=list)  # точные фразы из текста


