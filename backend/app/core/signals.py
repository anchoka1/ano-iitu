# Слова-маркеры мнения (для /правда): мнение не бывает «правдой» или «ложью».
OPINION_PATTERNS = (r"\b(я\s+считаю|по-моему|по\s+моему\s+мнению|мне\s+кажется|лучш\w+|худш\w+|ужасн\w+|прекрасн\w+|самый)\b",)

_COMPILED: dict[str, list[re.Pattern[str]]] = {}


def _compiled(rule: SignalRule) -> list[re.Pattern[str]]:
    # Компилируем шаблоны один раз и запоминаем (это ускоряет повторные проверки).
    if rule.id not in _COMPILED:
        _COMPILED[rule.id] = [re.compile(p, re.IGNORECASE) for p in rule.patterns]
    return _COMPILED[rule.id]


def find_signals(text: str, rules: tuple[SignalRule, ...] = SCAM_RULES) -> list[SignalHit]:
    """Ищет признаки в тексте. Возвращает список сработавших правил с цитатами."""
    hits: list[SignalHit] = []
    for rule in rules:
        quotes: list[str] = []
        for pattern in _compiled(rule):
            for match in pattern.finditer(text):
                quote = match.group(0).strip()
                if quote and quote.lower() not in (q.lower() for q in quotes):
                    quotes.append(quote)
        if quotes:
            hits.append(SignalHit(rule.id, rule.title, rule.explanation, rule.weight, quotes[:3]))
    # Сначала самые «тяжёлые» признаки
    hits.sort(key=lambda h: h.weight, reverse=True)
    return hits


def is_opinion(text: str) -> bool:
    return any(re.search(p, text, re.IGNORECASE) for p in OPINION_PATTERNS)


def risk_score(hits: list[SignalHit]) -> int:
    return sum(h.weight for h in hits)
